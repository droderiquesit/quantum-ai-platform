//! `qip-agency`: the contracts a causal action engine must satisfy before it
//! may plan anything (blueprint §24, AGENCY domain).
//!
//! Nothing here acts. Every type is a refusal-at-construction record: a goal
//! missing one of its twelve declarations, a tool missing one of its six, a
//! candidate set without a no-action baseline, an attribution without a
//! causal chain. A malformed value that cannot be built cannot be planned,
//! simulated or executed, which is the structural form of "wanting an outcome
//! grants no permission to act".
//!
//! Status: one composition root reaches this crate. `qip agency shadow`
//! (`qip-cli`) loads the agency policy from configuration — conduct rules,
//! registered tools, the eligibility register, the action policies — and
//! refuses to run without it; builds one [`guard::ActionGuard`] and keeps it
//! across every pass, resumed from the journal; runs each request through
//! [`engine::run_governed`]; and journals every pass's approvals, tool
//! decisions and verdict on the hash-chained log through [`journal`]. It may
//! widen a policy through [`engine::widen`], on an attribution an
//! [`estimate`] reproduces. Its adapter refuses every call (ADR 0114), so a
//! pass at narrow-reversible authority is attempted, recorded and refused,
//! and nothing is sent.
//!
//! The second composition root is `qip-deepbrain`'s run loop: every ambient
//! signal the research sweep routes and the attention router activates is
//! offered to [`ambient_intake::AmbientIntake`], the one door from the
//! ambient mesh to the agency (R12-AGENCY-7029): promotion, then the same
//! guard, then the drafting adapter of [`outbox`], whose only effect is an
//! append to an internal outbox (ADR 0114 Amendment 1). Nothing external is
//! reachable through it.
//!
//! Inside the crate, [`engine::execute`] is the only adapter caller and it
//! stands [`guard::ActionGuard`] in front of every call: the conduct gate,
//! the tool registry, the approval chain and the justification check.
//! Candidates are compared on all nine axes ([`comparison`]), may be
//! generated by the planner itself and are simulated across competing
//! structural models and scenario branches ([`generate`], [`causal`]).
//! [`engine::learn`] writes [`memory`] and drives [`autonomy`]'s drift rule.
//! It runs after an executed act on a measured outcome, and no shipped binary
//! executes one (ADR 0114); it also runs after a *shadowed* act, on the
//! outcome the pass itself simulated, declared simulated on the record
//! ([`simulated`], [`engine::learn_shadowed`]). `qip agency shadow` calls it
//! that way after every shadowed pass with a structural model, journals the
//! update beside the pass, and journals a withheld learning, with the reason,
//! where the outcome needed is absent.
//!
//! [`goal`], [`tools`] and [`attribution`] re-export `qip-contracts` types:
//! each used to exist twice, once here and once there.

