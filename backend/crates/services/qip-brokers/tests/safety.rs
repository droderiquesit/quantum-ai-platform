//! The three refusals this crate exists to make structural.
//!
//! * **A secret cannot be printed or serialised.** Not "is not, by convention" —
//!   cannot. The redacting `Debug` and `Display` are checked directly, the
//!   serialised form of a credential holding a secret is searched for it, and
//!   so are the error messages and the adapter's own `Debug` output after a
//!   logon. Every one of those is a real path a token has escaped through in a
//!   real system.
//! * **There is no live venue.** [`AdapterClass`] has no `Live` variant, so
//!   nothing deserialises into one and nothing constructs one. The compile-time
//!   half of that claim is a `compile_fail` doctest in the crate root; this is
//!   the half a configuration file could otherwise get past.
//! * **An order cannot reach a venue that is not ready.** The ticket is proof
//!   about a moment, not a flag, and the tests below try every way of holding
//!   one that has stopped being true.
//!
//! The string used to prove redaction is a marker, not a credential: it is
//! generated by this file, means nothing to anything, and is here so that a
//! test asserting "the output does not contain the secret" is not quietly
//! passing because the secret was empty.

