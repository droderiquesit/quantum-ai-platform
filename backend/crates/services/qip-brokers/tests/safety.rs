#[test]
fn every_fill_the_venue_produces_is_marked_simulated() -> Result<()> {
    let mut exchange = SimulatedExchange::new(venue(), ExchangeSettings::orderly(), 42, start());
    exchange.list(instrument());
    exchange.seed_liquidity(
        &object(),
        Side::Sell,
        dec!("100.02"),
        Decimal::from_int(50),
        start(),
    )?;
    exchange.bring_up(&credential_holding_a_secret(), start())?;

    assert_eq!(exchange.class(), AdapterClass::Simulated);
    assert!(exchange.is_simulated());

    let ticket = exchange.ready(start())?;
    let ack = exchange.submit_order(&ticket, &order("marked", Side::Buy, 30), start())?;
    assert!(ack.simulated);
    assert!(!ack.fills.is_empty());
    assert!(ack.fills.iter().all(|fill| fill.simulated));
    assert!(
        exchange
            .query_fills(None)?
            .iter()
            .all(|fill| fill.simulated)
    );
    assert!(
        exchange
            .drain_bookable_fills()
            .iter()
            .all(|bookable| bookable.fill.simulated)
    );
    Ok(())
}

#[test]
fn the_adapter_overwrites_a_fill_that_claims_to_be_real() {
    // A venue message does not get a vote on the single most consequential bit
    // in the execution path.
    let mut forged = vec![Fill {
        fill_id: FillId::from_string("forged"),
        order_id: OrderId::from_string("forged"),
        at: start(),
        quantity: Decimal::from_int(1),
        price: dec!("100"),
        costs: Decimal::ZERO,
        venue: VENUE.to_string(),
        simulated: false,
    }];
    stamp_simulated(&mut forged, true);
    assert!(forged.iter().all(|fill| fill.simulated));
}

// --- an order cannot reach a venue that is not ready ------------------------

#[test]
fn a_session_cannot_skip_a_step() {
    let mut connection = ConnectionState::new(venue(), Duration::from_secs(30), start());
    assert_eq!(connection.phase(), ConnectionPhase::Disconnected);

    // Disconnected is not authenticated, and a socket is not a session.
    assert_eq!(
        connection
            .authenticated(start(), ACCOUNT)
            .expect_err("no transport")
            .code(),
        "invalid"
    );
    assert_eq!(
        connection
            .make_ready(start())
            .expect_err("nothing to promote")
            .code(),
        "invalid"
    );
    assert_eq!(
        connection
            .ready_ticket(start())
            .expect_err("no session")
            .code(),
        "denied"
    );
    assert_eq!(
        connection
            .observe_heartbeat(start())
            .expect_err("no session")
            .code(),
        "denied"
    );

    connection
        .connect(start())
        .expect("a transport may always be opened from disconnected");
    assert_eq!(
        connection
            .make_ready(start())
            .expect_err("a socket is not a logon")
            .code(),
        "invalid"
    );

    connection
        .authenticated(start(), ACCOUNT)
        .expect("logon after connect");
    let error = connection
        .make_ready(start())
        .expect_err("a session nobody has heard from is not a session that works");
    assert_eq!(error.code(), "invalid");
    assert!(error.message().contains("heartbeat"), "{}", error.message());

    connection
        .observe_heartbeat(start())
        .expect("the venue answers");
    assert_eq!(connection.phase(), ConnectionPhase::Ready);
    assert!(connection.ready_ticket(start()).is_ok());
}

#[test]
fn a_ticket_is_proof_about_a_moment_and_not_a_flag() {
    let mut connection = ConnectionState::new(venue(), Duration::from_secs(30), start());
    connection.connect(start()).expect("connect");
    connection.authenticated(start(), ACCOUNT).expect("logon");
    connection.observe_heartbeat(start()).expect("heartbeat");
    let ticket = connection.ready_ticket(start()).expect("ready");

    // The same ticket, later, after the venue has gone quiet.
    let later = start().saturating_add(Duration::from_secs(90));
    let error = connection
        .authorise(&ticket, later)
        .expect_err("the moment has passed");
    assert_eq!(error.code(), "denied");
    assert!(error.message().contains("degraded"), "{}", error.message());

    // The same ticket, after the session was rebuilt underneath it.
    connection.disconnect(start(), "rebuilding");
    connection.connect(start()).expect("connect");
    connection.authenticated(start(), ACCOUNT).expect("logon");
    connection.observe_heartbeat(start()).expect("heartbeat");
    let error = connection
        .authorise(&ticket, start())
        .expect_err("a new session is not the old one");
    assert_eq!(error.code(), "denied");
    assert!(error.message().contains("session"), "{}", error.message());
}

#[test]
fn a_ticket_for_one_venue_authorises_nothing_at_another() {
    let mut here = ConnectionState::new(venue(), Duration::from_secs(30), start());
    here.connect(start()).expect("connect");
    here.authenticated(start(), ACCOUNT).expect("logon");
    here.observe_heartbeat(start()).expect("heartbeat");
    let ticket = here.ready_ticket(start()).expect("ready");
    assert_eq!(ticket.venue(), VENUE);
    assert_eq!(ticket.issued_at(), start());

    let mut elsewhere =
        ConnectionState::new(VenueId::new("XOTHER"), Duration::from_secs(30), start());
    elsewhere.connect(start()).expect("connect");
    elsewhere.authenticated(start(), ACCOUNT).expect("logon");
    elsewhere.observe_heartbeat(start()).expect("heartbeat");

    let error = elsewhere
        .authorise(&ticket, start())
        .expect_err("tickets are not transferable");
    assert_eq!(error.code(), "denied");
}

#[test]
fn a_session_that_goes_quiet_is_degraded_whether_or_not_anybody_looks() {
    let mut connection = ConnectionState::new(venue(), Duration::from_secs(30), start());
    connection.connect(start()).expect("connect");
    connection.authenticated(start(), ACCOUNT).expect("logon");
    connection.observe_heartbeat(start()).expect("heartbeat");

    let later = start().saturating_add(Duration::from_secs(31));
    // Pure: reporting a stale `ready` because nobody happened to call a
    // mutating method is the exact failure this crate exists to avoid.
    assert_eq!(connection.phase(), ConnectionPhase::Ready);
    assert_eq!(connection.effective_phase(later), ConnectionPhase::Degraded);
    assert!(connection.heartbeat_overdue(later));
    assert_eq!(
        connection.heartbeat_gap(later),
        Some(Duration::from_secs(31))
    );

    assert_eq!(connection.observe(later), ConnectionPhase::Degraded);
    assert_eq!(connection.phase(), ConnectionPhase::Degraded);
    // A cancel still has a session to travel on.
    assert!(connection.require_session(later).is_ok());
    // Observing twice must not try an illegal transition.
    assert_eq!(connection.observe(later), ConnectionPhase::Degraded);
    assert!(connection.transitions().len() >= 4);
}

