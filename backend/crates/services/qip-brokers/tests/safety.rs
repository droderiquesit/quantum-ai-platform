/// A marker that is not a credential and authenticates nothing.
///
/// Its only job is to be findable. A test that searches output for a secret
/// proves nothing unless the secret was distinctive and actually present, so
/// every assertion below is paired with one showing this string *is* in the
/// credential it claims is not leaking it.
const MARKER: &str = "marker-string-that-must-never-appear-in-output";

const VENUE: &str = "XSIM";
const ACCOUNT: &str = "book-under-test";

fn start() -> Timestamp {
    Timestamp::from_civil(2026, 8, 24)
}

fn venue() -> VenueId {
    VenueId::new(VENUE)
}

fn object() -> ObjectId {
    ObjectId::from_string("OBJ00000000000000000000AAA")
}

fn session_credential_name() -> String {
    standard_requirements(&venue())
        .into_iter()
        .find(|requirement| requirement.kind == RequirementKind::SessionCredential)
        .map(|requirement| requirement.name)
        .expect("the standard list always names a session credential")
}

/// A credential carrying a resolved value, which is the dangerous shape.
fn credential_holding_a_secret() -> VenueCredential {
    let enforced = requirements_of_kind(
        &standard_requirements(&venue()),
        &[RequirementKind::Account, RequirementKind::SessionCredential],
    );
    let mut credential =
        VenueCredential::satisfying(VENUE, ACCOUNT, &enforced).expect("a named venue and account");
    credential = credential.with_secret(
        session_credential_name(),
        format!("QIP_{VENUE}_CREDENTIAL"),
        Secret::new(MARKER),
    );
    credential
}

// --- a secret cannot be printed or serialised -------------------------------

#[test]
fn a_secret_redacts_in_debug_and_display() {
    let secret = Secret::new(MARKER);

    // Non-vacuity first: the value really is in there.
    assert_eq!(secret.expose_str().expect("valid text"), MARKER);
    assert!(!secret.is_empty());

    assert_eq!(format!("{secret:?}"), "Secret(<redacted>)");
    assert_eq!(format!("{secret}"), "<redacted>");
    // Not even the length, which is a hint, or a prefix, which is a head start.
    assert!(!format!("{secret:?}").contains(&MARKER.len().to_string()));
    assert!(!format!("{secret:?}").contains(&MARKER[..8]));
}

#[test]
fn a_secret_inside_a_struct_still_redacts() {
    // A `Debug` derived on a wrapper delegates to the field's `Debug`, which is
    // the path by which a secret usually reaches a log: nobody prints the
    // secret, somebody prints the struct that holds it.
    #[derive(Debug)]
    struct Session {
        account: &'static str,
        secret: Secret,
    }

    let session = Session {
        account: ACCOUNT,
        secret: Secret::new(MARKER),
    };
    let rendered = format!("{session:?}");
    // Non-vacuity: the wrapper really does hold the marker, and its other field
    // really does print.
    assert_eq!(session.secret.expose_str().expect("valid text"), MARKER);
    assert!(
        rendered.contains(session.account),
        "the harmless field should still print: {rendered}"
    );
    assert!(
        !rendered.contains(MARKER),
        "a derived Debug must not defeat the redaction: {rendered}"
    );
}

#[test]
fn a_credential_never_serialises_the_secret_it_carries() -> Result<()> {
    let credential = credential_holding_a_secret();
    let name = session_credential_name();

    // Non-vacuity: the credential really is holding the marker.
    assert_eq!(credential.resolved_count(), 1);
    assert_eq!(
        credential
            .secret(&name)
            .expect("the secret is present")
            .expose_str()?,
        MARKER
    );

    let json = serde_json::to_string(&credential).expect("a credential serialises");
    assert!(
        !json.contains(MARKER),
        "a secret reached a serialised form: {json}"
    );
    // What *should* be there: the reference, which is a configuration note.
    assert!(json.contains(&format!("QIP_{VENUE}_CREDENTIAL")), "{json}");
    assert!(json.contains(ACCOUNT), "{json}");

    assert!(!format!("{credential:?}").contains(MARKER));
    assert!(!format!("{credential}").contains(MARKER));
    assert!(format!("{credential:?}").contains("redacted"));

    // A credential that came off the wire has references and no values: a
    // secret never left over it, so it cannot arrive over it either.
    let restored: VenueCredential = serde_json::from_str(&json).expect("a credential deserialises");
    assert_eq!(restored.resolved_count(), 0);
    assert!(restored.secret(&name).is_none());
    assert_eq!(
        restored.reference(&name),
        Some(format!("QIP_{VENUE}_CREDENTIAL").as_str())
    );
    assert_eq!(restored.account(), ACCOUNT);
    assert_eq!(restored.venue(), VENUE);
    Ok(())
}

#[test]
fn a_refusal_names_the_requirement_and_not_the_value() {
    let credential = credential_holding_a_secret();
    let elsewhere = VenueId::new("XOTHER");

    let error = credential
        .require(&elsewhere, &standard_requirements(&elsewhere))
        .expect_err("a credential is not transferable between venues");
    assert_eq!(error.code(), "denied");
    assert!(!error.message().contains(MARKER), "{}", error.message());
    assert!(!format!("{error}").contains(MARKER));

    let error = credential
        .require(&venue(), &standard_requirements(&venue()))
        .expect_err("the standard list is longer than what a simulator enforces");
    assert_eq!(error.code(), "unavailable");
    assert!(!error.message().contains(MARKER), "{}", error.message());
    assert!(
        error.message().contains("QIP_XSIM_ENDPOINT"),
        "{}",
        error.message()
    );
}

#[test]
fn an_adapter_that_authenticated_with_a_secret_does_not_hold_it() -> Result<()> {
    let mut exchange = SimulatedExchange::new(venue(), ExchangeSettings::orderly(), 41, start());
    exchange.list(instrument());
    exchange.bring_up(&credential_holding_a_secret(), start())?;

    assert_eq!(exchange.account(), Some(ACCOUNT));
    let rendered = format!("{exchange:?}");
    assert!(
        rendered.contains(ACCOUNT),
        "the account is not a secret and should be visible"
    );
    assert!(
        !rendered.contains(MARKER),
        "the adapter kept the secret where a log could find it"
    );

    // The health report is serialised into events and dashboards.
    let health = serde_json::to_string(&exchange.health(start())).expect("health serialises");
    assert!(!health.contains(MARKER), "{health}");
    Ok(())
}

