#[test]
fn a_credential_has_no_default_venue_and_no_default_account() {
    assert_eq!(
        VenueCredential::new("  ", ACCOUNT)
            .expect_err("blank venue")
            .code(),
        "invalid"
    );
    let error = VenueCredential::new(VENUE, "   ").expect_err("blank account");
    assert_eq!(error.code(), "invalid");
    assert!(
        error.message().contains("no default account"),
        "{}",
        error.message()
    );
}

#[test]
fn an_incomplete_credential_is_refused_with_the_list_of_what_is_missing() -> Result<()> {
    let requirements = standard_requirements(&venue());
    let empty = VenueCredential::new(VENUE, ACCOUNT)?;
    assert!(empty.is_empty());
    assert_eq!(empty.missing(&requirements).len(), requirements.len());

    let error = empty
        .require(&venue(), &requirements)
        .expect_err("nothing is satisfied");
    assert_eq!(error.code(), "unavailable");
    for requirement in &requirements {
        assert!(
            error.message().contains(&requirement.env_var),
            "the refusal must name {}: {}",
            requirement.env_var,
            error.message()
        );
    }

    // The same sentence, reached directly.
    assert_eq!(
        describe_missing(&venue(), &requirements),
        error.message(),
        "one refusal, worded once"
    );
    assert_eq!(
        describe_missing(&venue(), &[]),
        "XSIM needs nothing further"
    );
    Ok(())
}

#[test]
fn a_simulator_enforces_only_what_it_can_honestly_check() -> Result<()> {
    let requirements = standard_requirements(&venue());
    // Six items, of which a simulator can genuinely check two: it cannot dial
    // an endpoint it does not have or verify an entitlement nobody granted.
    assert_eq!(requirements.len(), 6);
    let enforceable = requirements_of_kind(
        &requirements,
        &[RequirementKind::Account, RequirementKind::SessionCredential],
    );
    assert_eq!(enforceable.len(), 2);

    let credential = VenueCredential::satisfying(VENUE, ACCOUNT, &enforceable)?;
    credential.require(&venue(), &enforceable)?;
    // And it still reports itself incomplete as a venue.
    assert_eq!(credential.missing(&requirements).len(), 4);

    let mut exchange = SimulatedExchange::new(venue(), ExchangeSettings::orderly(), 43, start());
    exchange.list(instrument());
    assert_eq!(exchange.missing_requirements().len(), 6);
    exchange.bring_up(&credential, start())?;
    assert_eq!(
        exchange.missing_requirements().len(),
        6,
        "a logon does not complete a venue"
    );
    Ok(())
}

#[test]
fn requirements_say_which_ones_a_deployment_can_satisfy_by_itself() {
    let requirements = standard_requirements(&venue());
    let self_service: Vec<&VenueRequirement> = requirements
        .iter()
        .filter(|requirement| requirement.kind.is_self_service())
        .collect();
    // An endpoint and a protocol parameter are configuration changes; an
    // entitlement needs somebody at the venue to act, and that is days.
    assert_eq!(self_service.len(), 2);
    assert!(!RequirementKind::Entitlement.is_self_service());
    assert!(!RequirementKind::SessionCredential.is_self_service());

    for requirement in &requirements {
        let described = requirement.describe();
        assert!(described.contains(&requirement.env_var), "{described}");
        assert!(described.contains(requirement.kind.as_str()), "{described}");
        // The same requirement, in the vocabulary the routing gateways use, so
        // the two frameworks cannot disagree about what a venue is missing.
        let gateway = requirement.as_gateway_credential();
        assert_eq!(gateway.env_var, requirement.env_var);
        assert_eq!(gateway.purpose, requirement.purpose);
    }
}

#[test]
fn authentication_refuses_a_credential_for_another_venue() -> Result<()> {
    let mut exchange = SimulatedExchange::new(venue(), ExchangeSettings::orderly(), 44, start());
    exchange.list(instrument());
    let elsewhere = VenueId::new("XOTHER");
    let enforceable = requirements_of_kind(
        &standard_requirements(&elsewhere),
        &[RequirementKind::Account, RequirementKind::SessionCredential],
    );
    let wrong = VenueCredential::satisfying("XOTHER", ACCOUNT, &enforceable)?;

    let error = exchange
        .bring_up(&wrong, start())
        .expect_err("not this venue's credential");
    assert_eq!(error.code(), "denied");
    assert_eq!(
        exchange.account(),
        None,
        "a refused logon must not name an account"
    );
    assert!(exchange.ready(start()).is_err());
    Ok(())
}

